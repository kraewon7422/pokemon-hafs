-- 0056: 포켓몬 교환 (친구와 얼굴 보고 1 대 1, 배틀 QR 로)
--  흐름
--   · A 가 '내 배틀 QR' 을 보여 줌 → B 가 찍으면 [포켓몬 교환하기] → trade_open(code) = 교환방 (p1 = B 찍은 사람, p2 = A QR 주인).
--     A 의 폰은 QR 화면에서 1.5초마다 trade_current() 로 방을 알아채고 교환방을 엶. 두 사람 모두 trade_state(id) 로 1.5초마다 새로 봄.
--   · 각자 박스에서 한 마리 고름 (trade_offer) → 서로의 포켓몬이 보임 (그림 · 이름 · 레벨 · 특성 · 기술) → 둘 다 [교환하기] (trade_confirm(id, rev)).
--     고른 포켓몬이 바뀌면 rev 가 올라가고 두 사람의 '교환하기' 가 풀림 (본 것과 다른 포켓몬으로 바뀌는 일 없음 = rev 가 같아야 확인).
--     교환이 끝나기 전에는 누구든 trade_cancel. 아무것도 안 하고 trade_room_sec (기본 180초) 이 지나면 방이 사라짐 (expired).
--     두 번째로 누른 사람의 확인에서 바로 바꿈 (_trade_swap, 한 트랜잭션). 먼저 누른 사람이 20초 넘게 화면에 없으면 TRADE_PARTNER_AWAY.
--  교환할 수 있는 포켓몬 = 일반 폼 (form_kind 'normal' — 야생 · 사파리 · 알에서 나온 보통 포켓몬) 만. 서버가 언제나 다시 확인 (_trade_why):
--     반짝이 TRADE_SHINY · 선생님 폼 TRADE_TEACHER · 이벤트 폼 (지우의 피카츄 …) TRADE_EVENT · 학교 특별 (교장/교감 · 비밀 · 환상 …) TRADE_SPECIAL ·
--     울트라비스트 TRADE_ULTRA · 전설 (rarity legendary · mythic · legend_src) TRADE_LEGEND · 카드 포켓몬 TRADE_PARTNER · 저장한 배틀 팀 TRADE_IN_TEAM ·
--     배틀/레이드에 나가 있음 TRADE_BUSY · 내 박스에 없음 TRADE_NO_MON. (알은 박스에 없으므로 교환 대상이 아님)
--  바꾸기 = 두 줄의 주인 (user_id) 을 서로 바꿈 → 잡기 수 · 타입별 수 · 점수는 '옮겨 감' (둘이 계속 주고받아도 늘지 않음).
--     레벨 · 경험치 · 기술 · 특성 · 갈래 그대로. 지닌 물건 = 보낸 사람 가방으로. 박스 자리 = 받는 사람의 빈 칸 중 맨 앞 (한 마리 주고 한 마리 받으니 언제나 있음).
--     ot_user = 처음 잡은 트레이너 (한 번 정해지면 그대로), traded_at.
--  도감
--     · 보낸 사람: 보낸 포켓몬의 종 (진화 앞 단계 포함) 을 trade_seen 에 남김 → 도감 (잡은 적 있음) 은 그대로 (_seen_species 가 합침).
--     · 받은 사람: 도감에 새로 등록 — 단 '되돌려 받기' 는 안 셈 (collection.no_dex = true):
--         (a) 예전에 내가 보냈던 바로 그 포켓몬이 돌아옴 (예: 고우스트를 보내 팬텀으로 진화시켜 돌려받기), 또는
--         (b) 최근 24시간 안에 내가 같은 상대에게 같은 가족 (lines.family_id) 의 포켓몬을 보낸 적이 있음 (같은 종을 주고받기).
--       no_dex 줄은 도감 · 도감 수에 안 들어감 (나중에 또 보내도 trade_seen 에 안 남음). 교환은 일반 폼만이라 학교 도감 · 해금 · 부적에는 영향 없음.
--  교환 진화 (실제 게임처럼): 받은 포켓몬이 윤겔라 · 근육몬 · 데구리 · 고우스트 · 암트르 · 토쇠골 (일반 폼, 갈래 없음) 이면 도착하자마자 다음 단계로.
--  막기: 운영자 스위치 trade_open (기본 켬) · 하루 trade_daily_max 번 (기본 5, 두 사람 각자) · 한 사람당 열린 교환방 하나 · 모든 일 events (kind 'trade').
--  운영자: admin_trades(p_limit) = 오늘 교환 수 · 열린 방 · 최근 교환 목록.

