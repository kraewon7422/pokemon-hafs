-- 고르기 (p_mon null = 내려놓기). 바뀌면 두 사람의 '교환하기' 가 풀림
create or replace function public.trade_offer(p_id bigint, p_mon bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); t public.trades; w text; me int;
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;
  perform public._trade_tidy(uid);
  select * into t from public.trades where id = p_id and (p1 = uid or p2 = uid) for update;
  if not found then raise exception 'TRADE_NOT_FOUND'; end if;
  if t.status <> 'open' then return public._trade_json(t, uid); end if;
  me := case when t.p1 = uid then 1 else 2 end;
  if p_mon is not null then
    w := public._trade_why(uid, p_mon);
    if w is not null then raise exception '%', w; end if;
  end if;
  if (case when me = 1 then t.m1 else t.m2 end) is not distinct from p_mon then
    update public.trades set touched_at = now() where id = p_id returning * into t;
    return public._trade_json(t, uid);
  end if;
  update public.trades set m1 = case when me = 1 then p_mon else m1 end, m2 = case when me = 2 then p_mon else m2 end,
         ok1 = false, ok2 = false, rev = rev + 1, note = null, touched_at = now(),
         seen1 = case when me = 1 then now() else seen1 end, seen2 = case when me = 2 then now() else seen2 end
   where id = p_id returning * into t;
  return public._trade_json(t, uid);
end $$;

-- 교환하기 (p_rev = 화면에 보인 rev). 둘 다 누르면 그 자리에서 바꿈. 이미 끝난 교환이면 결과를 그대로 (두 번 눌러도 한 번)
create or replace function public.trade_confirm(p_id bigint, p_rev int) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); t public.trades; me int; w1 text; w2 text; oseen timestamptz; mx int := public._trade_max();
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;
  perform public._trade_tidy(uid);
  select * into t from public.trades where id = p_id and (p1 = uid or p2 = uid) for update;
  if not found then raise exception 'TRADE_NOT_FOUND'; end if;
  if t.status <> 'open' then return public._trade_json(t, uid); end if;
  me := case when t.p1 = uid then 1 else 2 end;
  if p_rev is distinct from t.rev then raise exception 'TRADE_CHANGED'; end if;
  if t.m1 is null or t.m2 is null then raise exception 'TRADE_NEED_BOTH'; end if;
  update public.trades set ok1 = ok1 or me = 1, ok2 = ok2 or me = 2, touched_at = now(),
         seen1 = case when me = 1 then now() else seen1 end, seen2 = case when me = 2 then now() else seen2 end
   where id = p_id returning * into t;
  if not (t.ok1 and t.ok2) then return public._trade_json(t, uid); end if;
  -- 두 사람 모두 확인 → 바꾸기 전에 다시 확인 (빠진 포켓몬은 내려놓고 확인을 풀어 알려 줌)
  oseen := case when me = 1 then t.seen2 else t.seen1 end;
  if oseen is null or oseen < now() - interval '20 seconds' then raise exception 'TRADE_PARTNER_AWAY'; end if;
  w1 := public._trade_why(t.p1, t.m1);
  w2 := public._trade_why(t.p2, t.m2);
  if w1 is not null or w2 is not null then
    update public.trades set m1 = case when w1 is not null then null else m1 end, m2 = case when w2 is not null then null else m2 end,
           ok1 = false, ok2 = false, rev = rev + 1, note = coalesce(w1, w2)
     where id = p_id returning * into t;
    return public._trade_json(t, uid);
  end if;
  if not public._trade_on() or public._trade_count(t.p1) >= mx or public._trade_count(t.p2) >= mx then
    update public.trades set status = 'cancelled', ended_at = now(), ended_why = case when public._trade_on() then 'daily_max' else 'closed' end
     where id = p_id returning * into t;
    return public._trade_json(t, uid);
  end if;
  perform public._trade_swap(p_id);
  select * into t from public.trades where id = p_id;
  return public._trade_json(t, uid);
end $$;

create or replace function public.trade_cancel(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); t public.trades;
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;
  select * into t from public.trades where id = p_id and (p1 = uid or p2 = uid) for update;
  if not found then raise exception 'TRADE_NOT_FOUND'; end if;
  if t.status = 'open' then
    update public.trades set status = 'cancelled', ended_at = now(), ended_by = uid, ended_why = 'cancel' where id = p_id returning * into t;
    insert into public.events (user_id, kind, data) values (uid, 'trade', jsonb_build_object('act', 'cancel', 'trade', p_id));
  end if;
  return public._trade_json(t, uid);
end $$;

-- 내 박스에서 교환할 수 없는 포켓몬과 이유 {포켓몬 번호: 코드} + 오늘 교환 수
create or replace function public.trade_check() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare uid uuid := auth.uid();
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;
  return jsonb_build_object(
    'why', coalesce((select jsonb_object_agg(c.id::text, w) from (
                       select c.id, public._trade_why(uid, c.id) w from public.collection c where c.user_id = uid and c.released_at is null) c
                     where w is not null), '{}'),
    'today', public._trade_count(uid), 'max', public._trade_max(), 'open', public._trade_on());
end $$;

-- ── 5. 운영자 ──────────────────────────────────────────────────────────────────────────────────────────────────
create or replace function public.admin_trades(p_limit int default 30) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public._assert_admin();
  return jsonb_build_object(
    'today', (select count(*) from public.trades where status = 'done' and done_at >= public._today_start()),
    'open', (select count(*) from public.trades where status = 'open' and touched_at > now() - make_interval(secs => public._trade_sec())),
    'rows', coalesce((select jsonb_agg(x order by x.at desc) from (
       select t.id, coalesce(t.done_at, t.ended_at, t.created_at) as at, t.status, t.ended_why as why,
              a.student_id as a_sid, public._display_name(a) as a_name, b.student_id as b_sid, public._display_name(b) as b_name,
              t.sp1, t.sp2, t.result -> '2' -> 'evolved_to' as evo1, t.result -> '1' -> 'evolved_to' as evo2
         from public.trades t join public.profiles a on a.user_id = t.p1 join public.profiles b on b.user_id = t.p2
        order by t.id desc limit least(200, greatest(1, coalesce(p_limit, 30)))) x), '[]'));
end $$;

