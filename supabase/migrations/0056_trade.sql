create table if not exists public.trade_seen (
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  species_id int not null,
  at timestamptz not null default now(),
  primary key (user_id, species_id)
);
alter table public.trade_seen enable row level security;

create table if not exists public.trades (
  id bigint generated by default as identity primary key,
  p1 uuid not null references public.profiles(user_id) on delete cascade,   -- QR 을 찍은 사람
  p2 uuid not null references public.profiles(user_id) on delete cascade,   -- QR 을 보여 준 사람
  status text not null default 'open' check (status in ('open', 'done', 'cancelled', 'expired')),
  m1 bigint, m2 bigint,                    -- 고른 포켓몬 (collection.id)
  ok1 boolean not null default false, ok2 boolean not null default false,
  rev int not null default 0,              -- 고른 포켓몬이 바뀔 때마다 +1
  seen1 timestamptz, seen2 timestamptz,    -- 마지막으로 방을 본 때 (화면에 있는지)
  note text,                               -- 마지막 알림 (예: 바꾸기 직전 다시 확인에서 빠진 이유)
  created_at timestamptz not null default now(),
  touched_at timestamptz not null default now(),
  ended_at timestamptz, ended_by uuid, ended_why text,
  done_at timestamptz,
  line1 int, line2 int, sp1 int, sp2 int,  -- 바꿀 때의 계열 · 종 (보낸 쪽 기준)
  result jsonb
);
alter table public.trades enable row level security;
create index if not exists trades_open_p1 on public.trades (p1) where status = 'open';
create index if not exists trades_open_p2 on public.trades (p2) where status = 'open';
create index if not exists trades_done_at on public.trades (done_at) where status = 'done';

-- ── 2. 도감: 보낸 포켓몬은 trade_seen 으로 남고, 되돌려 받은 포켓몬 (no_dex) 은 안 셈 ─────────────────────────────
create or replace function public._seen_species(uid uuid) returns setof int
language sql stable security definer set search_path = '' as $$
  select x from public.collection c, unnest(public._sp_path(c.species_id)) x
   where c.user_id = uid and c.species_id is not null and not c.no_dex
  union
  select species_id from public.trade_seen where user_id = uid
$$;

-- ── 3. 도우미 ─────────────────────────────────────────────────────────────────────────────────────────────────
create or replace function public._trade_on() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((public._setting('trade_open'))::boolean, true)
$$;

create or replace function public._trade_max() returns int
language sql stable security definer set search_path = '' as $$
  select greatest(0, coalesce((public._setting('trade_daily_max'))::int, 5))
$$;

create or replace function public._trade_sec() returns int
language sql stable security definer set search_path = '' as $$
  select greatest(30, coalesce((public._setting('trade_room_sec'))::int, 180))
$$;

-- 오늘 (한국 시간) 끝낸 교환 수
create or replace function public._trade_count(uid uuid) returns int
language sql stable security definer set search_path = '' as $$
  select count(*)::int from public.trades
   where status = 'done' and (p1 = uid or p2 = uid) and done_at >= public._today_start()
$$;

create or replace function public._fam(p_line int) returns int
language sql stable security definer set search_path = '' as $$
  select coalesce(family_id, id) from public.lines where id = p_line
$$;

-- 교환할 수 없는 이유 (null = 교환 가능)
create or replace function public._trade_why(uid uuid, p_mon bigint) returns text
language plpgsql stable security definer set search_path = '' as $$
declare c public.collection; l public.lines; p public.profiles;
begin
  select * into c from public.collection where id = p_mon;
  if not found or c.user_id is distinct from uid or c.released_at is not null then return 'TRADE_NO_MON'; end if;
  select * into l from public.lines where id = c.line_id;
  if c.shiny then return 'TRADE_SHINY'; end if;
  if l.form_kind = 'teacher' then return 'TRADE_TEACHER'; end if;
  if l.form_kind = 'event' then return 'TRADE_EVENT'; end if;
  if l.form_kind is distinct from 'normal' or l.secret or l.bonus then return 'TRADE_SPECIAL'; end if;
  if l.ultra then return 'TRADE_ULTRA'; end if;
  if l.rarity = 'legendary' or l.mythic or l.legend_src is not null then return 'TRADE_LEGEND'; end if;
  select * into p from public.profiles where user_id = uid;
  if p.partner_mon = p_mon then return 'TRADE_PARTNER'; end if;
  if p_mon = any (coalesce(p.team_mons, '{}'::bigint[])) then return 'TRADE_IN_TEAM'; end if;
  if exists (select 1 from public.raid_players rp join public.raids r on r.id = rp.raid_id
              where rp.user_id = uid and rp.mon_id = p_mon and r.status = 'active') then return 'TRADE_BUSY'; end if;
  if exists (select 1 from public.battles b,
                    jsonb_array_elements(coalesce(b.state -> 'sides', '[]'::jsonb)) sd,
                    jsonb_array_elements(coalesce(sd -> 'mons', '[]'::jsonb)) m
              where b.status in ('active', 'invite') and (b.p1 = uid or b.p2 = uid)
                and sd ->> 'uid' = uid::text and m ->> 'mon' = p_mon::text) then return 'TRADE_BUSY'; end if;
  return null;
end $$;

-- 교환 진화: 받은 포켓몬 종 → 진화할 종 (없으면 null)
create or replace function public._trade_evo(p_sp int) returns int
language sql stable security definer set search_path = '' as $$
  select e.to_species from public.evolutions e
    join public.species s on s.id = e.from_species join public.lines l on l.id = s.line_id
   where e.from_species = p_sp and s.dex in (64, 67, 75, 93, 525, 533) and l.form_kind = 'normal'
     and (select count(*) from public.evolutions x where x.from_species = p_sp) = 1
   limit 1
$$;

create or replace function public._trade_mon_json(p_mon bigint) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('id', c.id, 'species_id', c.species_id, 'line', c.line_id, 'stage', c.stage, 'level', c.level,
                            'shiny', c.shiny, 'ability', c.ability, 'held', c.held, 'moves', to_jsonb(public._cur_moves(c.user_id, c.id)))
    from public.collection c where c.id = p_mon
$$;

-- 아무것도 안 한 지 trade_room_sec 이 지난 방 → expired
create or replace function public._trade_tidy(uid uuid) returns void
language sql security definer set search_path = '' as $$
  update public.trades set status = 'expired', ended_at = now(), ended_why = 'idle'
   where status = 'open' and (p1 = uid or p2 = uid) and touched_at < now() - make_interval(secs => public._trade_sec())
$$;

create or replace function public._trade_json(t public.trades, uid uuid) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare me int := case when t.p1 = uid then 1 else 2 end; other uuid := case when t.p1 = uid then t.p2 else t.p1 end;
  mm bigint := case when me = 1 then t.m1 else t.m2 end; tm bigint := case when me = 1 then t.m2 else t.m1 end;
  oseen timestamptz := case when me = 1 then t.seen2 else t.seen1 end;
begin
  return jsonb_build_object(
    'id', t.id, 'status', t.status, 'me', me, 'rev', t.rev,
    'name', (select public._display_name(p) from public.profiles p where p.user_id = other),
    'mine', case when t.status = 'open' and mm is not null then public._trade_mon_json(mm) end,
    'theirs', case when t.status = 'open' and tm is not null then public._trade_mon_json(tm) end,
    'ok_me', case when me = 1 then t.ok1 else t.ok2 end, 'ok_them', case when me = 1 then t.ok2 else t.ok1 end,
    'them_here', oseen is not null and oseen > now() - interval '20 seconds',
    'joined', oseen is not null,
    'note', t.note, 'why', t.ended_why, 'ended_by_me', t.ended_by = uid,
    'expires_at', t.touched_at + make_interval(secs => public._trade_sec()),
    'result', case when t.status = 'done' then t.result -> me::text end,
    'today', public._trade_count(uid), 'max', public._trade_max(),
    'server_time', now());
end $$;

-- 바꾸기 (trade_confirm 에서 두 사람이 모두 확인했을 때만). 모든 규칙을 이 순간 다시 확인, 이미 끝났으면 아무것도 안 함
create or replace function public._trade_swap(tid bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare t public.trades; c1 public.collection; c2 public.collection; w text;
  nd1 boolean; nd2 boolean; e1 int; e2 int; pos1 int; pos2 int; mx int := public._trade_max();
begin
  select * into t from public.trades where id = tid for update;
  if not found then raise exception 'TRADE_NOT_FOUND'; end if;
  if t.status = 'done' then return; end if;
  if t.status <> 'open' or not (t.ok1 and t.ok2) or t.m1 is null or t.m2 is null then raise exception 'TRADE_GONE'; end if;
  -- 두 박스를 같은 순서로 잠금 (_mon_new 와 같은 잠금)
  perform pg_advisory_xact_lock(hashtext('box:' || least(t.p1::text, t.p2::text)));
  perform pg_advisory_xact_lock(hashtext('box:' || greatest(t.p1::text, t.p2::text)));
  perform 1 from public.collection where id in (t.m1, t.m2) order by id for update;
  w := coalesce(public._trade_why(t.p1, t.m1), public._trade_why(t.p2, t.m2));
  if w is not null then raise exception '%', w; end if;
  if not public._trade_on() then raise exception 'TRADE_CLOSED'; end if;
  if public._trade_count(t.p1) >= mx or public._trade_count(t.p2) >= mx then raise exception 'TRADE_DAILY_MAX'; end if;
  select * into c1 from public.collection where id = t.m1;
  select * into c2 from public.collection where id = t.m2;

  -- 지닌 물건 → 보낸 사람 가방
  if c1.held is not null then
    insert into public.inventory (user_id, item, qty) values (t.p1, c1.held, 1) on conflict (user_id, item) do update set qty = public.inventory.qty + 1;
  end if;
  if c2.held is not null then
    insert into public.inventory (user_id, item, qty) values (t.p2, c2.held, 1) on conflict (user_id, item) do update set qty = public.inventory.qty + 1;
  end if;
  -- 보낸 사람 도감은 그대로
  insert into public.trade_seen (user_id, species_id) select t.p1, x from unnest(public._sp_path(c1.species_id)) x where not c1.no_dex on conflict do nothing;
  insert into public.trade_seen (user_id, species_id) select t.p2, x from unnest(public._sp_path(c2.species_id)) x where not c2.no_dex on conflict do nothing;
  -- 되돌려 받기 (도감에 안 셈): c1 이 p2 에게 / c2 가 p1 에게
  nd2 := exists (select 1 from public.trades x where x.status = 'done' and ((x.p1 = t.p2 and x.m1 = c1.id) or (x.p2 = t.p2 and x.m2 = c1.id)))
      or exists (select 1 from public.trades x where x.status = 'done' and x.done_at > now() - interval '24 hours'
                  and ((x.p1 = t.p2 and x.p2 = t.p1 and public._fam(x.line1) = public._fam(c1.line_id))
                    or (x.p2 = t.p2 and x.p1 = t.p1 and public._fam(x.line2) = public._fam(c1.line_id))));
  nd1 := exists (select 1 from public.trades x where x.status = 'done' and ((x.p1 = t.p1 and x.m1 = c2.id) or (x.p2 = t.p1 and x.m2 = c2.id)))
      or exists (select 1 from public.trades x where x.status = 'done' and x.done_at > now() - interval '24 hours'
                  and ((x.p1 = t.p1 and x.p2 = t.p2 and public._fam(x.line1) = public._fam(c2.line_id))
                    or (x.p2 = t.p1 and x.p1 = t.p2 and public._fam(x.line2) = public._fam(c2.line_id))));
  e2 := public._trade_evo(c1.species_id);   -- p2 가 받는 포켓몬
  e1 := public._trade_evo(c2.species_id);   -- p1 이 받는 포켓몬

  update public.collection set pos = null where id in (t.m1, t.m2);
  select min(g) into pos2 from generate_series(0, 899) g
   where not exists (select 1 from public.collection x where x.user_id = t.p2 and x.released_at is null and x.pos = g);
  if pos2 is null then raise exception 'BOX_FULL'; end if;
  update public.collection set user_id = t.p2, pos = pos2, held = null, shiny_on = false, no_dex = nd2,
         ot_user = coalesce(ot_user, t.p1), traded_at = now(), updated_at = now(),
         species_id = coalesce(e2, species_id), stage = coalesce((select stage from public.species where id = e2), stage),
         evo_fails = case when e2 is not null then 0 else evo_fails end
   where id = t.m1;
  select min(g) into pos1 from generate_series(0, 899) g
   where not exists (select 1 from public.collection x where x.user_id = t.p1 and x.released_at is null and x.pos = g);
  if pos1 is null then raise exception 'BOX_FULL'; end if;
  update public.collection set user_id = t.p1, pos = pos1, held = null, shiny_on = false, no_dex = nd1,
         ot_user = coalesce(ot_user, t.p2), traded_at = now(), updated_at = now(),
         species_id = coalesce(e1, species_id), stage = coalesce((select stage from public.species where id = e1), stage),
         evo_fails = case when e1 is not null then 0 else evo_fails end
   where id = t.m2;

  update public.trades set status = 'done', done_at = now(), ended_at = now(), touched_at = now(), note = null,
         line1 = c1.line_id, line2 = c2.line_id, sp1 = c1.species_id, sp2 = c2.species_id,
         result = jsonb_build_object(
           '1', jsonb_build_object('gave', c1.id, 'gave_sp', c1.species_id, 'got', c2.id, 'got_sp', c2.species_id, 'evolved_to', e1,
                                   'level', c2.level, 'no_dex', nd1, 'held_back', c1.held, 'pos', pos1),
           '2', jsonb_build_object('gave', c2.id, 'gave_sp', c2.species_id, 'got', c1.id, 'got_sp', c1.species_id, 'evolved_to', e2,
                                   'level', c1.level, 'no_dex', nd2, 'held_back', c2.held, 'pos', pos2))
   where id = tid;
  perform public._recompute(t.p1);
  perform public._recompute(t.p2);
  insert into public.events (user_id, kind, data) values
    (t.p1, 'trade', jsonb_build_object('act', 'done', 'trade', tid, 'with', t.p2, 'gave', c1.id, 'gave_sp', c1.species_id, 'gave_lv', c1.level,
                                       'got', c2.id, 'got_sp', c2.species_id, 'evolved_to', e1, 'no_dex', nd1)),
    (t.p2, 'trade', jsonb_build_object('act', 'done', 'trade', tid, 'with', t.p1, 'gave', c2.id, 'gave_sp', c2.species_id, 'gave_lv', c2.level,
                                       'got', c1.id, 'got_sp', c1.species_id, 'evolved_to', e2, 'no_dex', nd2));
end $$;

-- ── 4. 학생이 부르는 함수 ───────────────────────────────────────────────────────────────────────────────────────
-- 친구 배틀 QR 로 교환방 열기 (이미 둘의 방이 있으면 그 방)
create or replace function public.trade_open(p_code text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); fr uuid; t public.trades; mx int := public._trade_max();
begin
  if uid is null or not exists (select 1 from public.profiles where user_id = uid) then raise exception 'NOT_AUTHENTICATED'; end if;
  perform public._assert_open();
  if not public._trade_on() then raise exception 'TRADE_CLOSED'; end if;
  fr := public._bt_by_code(p_code);
  perform pg_advisory_xact_lock(hashtext('trade:' || least(uid::text, fr::text)));
  perform pg_advisory_xact_lock(hashtext('trade:' || greatest(uid::text, fr::text)));
  perform public._trade_tidy(uid);
  perform public._trade_tidy(fr);
  select * into t from public.trades where status = 'open' and ((p1 = uid and p2 = fr) or (p1 = fr and p2 = uid)) order by id desc limit 1;
  if found then
    update public.trades set touched_at = now(), seen1 = case when p1 = uid then now() else seen1 end, seen2 = case when p2 = uid then now() else seen2 end
     where id = t.id returning * into t;
    return public._trade_json(t, uid);
  end if;
  if exists (select 1 from public.trades where status = 'open' and (p1 = fr or p2 = fr)) then raise exception 'TRADE_FRIEND_BUSY'; end if;
  if public._trade_count(uid) >= mx then raise exception 'TRADE_DAILY_MAX'; end if;
  if public._trade_count(fr) >= mx then raise exception 'TRADE_FRIEND_DAILY_MAX'; end if;
  update public.trades set status = 'cancelled', ended_at = now(), ended_by = uid, ended_why = 'new_room'
   where status = 'open' and (p1 = uid or p2 = uid);
  insert into public.trades (p1, p2, seen1) values (uid, fr, now()) returning * into t;
  insert into public.events (user_id, kind, data) values (uid, 'trade', jsonb_build_object('act', 'open', 'trade', t.id, 'with', fr));
  return public._trade_json(t, uid);
end $$;

-- 지금 열린 내 교환방 (QR 을 보여 주는 동안 · 홈/배틀 탭에서 확인). 없으면 null
create or replace function public.trade_current() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); t public.trades;
begin
