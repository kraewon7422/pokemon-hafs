  perform public._trade_tidy(uid);
  select * into t from public.trades where status = 'open' and (p1 = uid or p2 = uid) order by id desc limit 1;
  if not found then return null; end if;
  return public._trade_json(t, uid);
end $$;

create or replace function public.trade_state(p_id bigint) returns jsonb
