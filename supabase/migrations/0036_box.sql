-- ── 10. 박스: 놓아주기 · 옮기기 ──────────────────────────────────────────────────────────────────────────────
create or replace function public.mon_release(p_mon bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p public.profiles := public._me_locked(); uid uuid := p.user_id; c public.collection;
begin
  select * into c from public.collection where id = p_mon and user_id = uid and released_at is null for update;
  if not found then raise exception 'NO_MONSTER'; end if;
  if public._box_count(uid) <= 1 then raise exception 'LAST_MON'; end if;
  if p.partner_mon = p_mon then raise exception 'MON_PARTNER'; end if;
  if p_mon = any (coalesce(p.team_mons, '{}'::bigint[])) then raise exception 'MON_IN_TEAM'; end if;
  if exists (select 1 from public.raid_players rp join public.raids r on r.id = rp.raid_id
              where rp.user_id = uid and rp.mon_id = p_mon and r.status = 'active') then raise exception 'MON_BUSY'; end if;
  if exists (select 1 from public.battles b,
                    jsonb_array_elements(coalesce(b.state -> 'sides', '[]'::jsonb)) sd,
                    jsonb_array_elements(coalesce(sd -> 'mons', '[]'::jsonb)) m
              where b.status in ('active', 'invite') and (b.p1 = uid or b.p2 = uid)
                and sd ->> 'uid' = uid::text and m ->> 'mon' = p_mon::text) then raise exception 'MON_BUSY'; end if;
  if c.held is not null then
    insert into public.inventory (user_id, item, qty) values (uid, c.held, 1)
      on conflict (user_id, item) do update set qty = public.inventory.qty + 1;
  end if;
  update public.collection set released_at = now(), pos = null, held = null, updated_at = now() where id = p_mon;
  insert into public.events (user_id, kind, data)
  values (uid, 'release', jsonb_build_object('mon', p_mon, 'line', c.line_id, 'stage', c.stage, 'level', c.level, 'held', c.held));
  return jsonb_build_object('ok', true, 'mon', p_mon, 'line', c.line_id, 'held_back', c.held, 'count', public._box_count(uid));
end $$;

create or replace function public.box_move(p_mon bigint, p_pos int) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p public.profiles := public._me_locked(); uid uuid := p.user_id; c public.collection; other bigint;
begin
  if p_pos is null or p_pos not between 0 and 899 then raise exception 'BAD_POS'; end if;
  select * into c from public.collection where id = p_mon and user_id = uid and released_at is null for update;
  if not found then raise exception 'NO_MONSTER'; end if;
  if c.pos = p_pos then return jsonb_build_object('ok', true, 'mon', p_mon, 'pos', p_pos, 'swap', null, 'swap_pos', null); end if;
  select id into other from public.collection where user_id = uid and released_at is null and pos = p_pos for update;
  update public.collection set pos = null where id = p_mon;
  if other is not null then update public.collection set pos = c.pos, updated_at = now() where id = other; end if;
  update public.collection set pos = p_pos, updated_at = now() where id = p_mon;
  return jsonb_build_object('ok', true, 'mon', p_mon, 'pos', p_pos, 'swap', other, 'swap_pos', case when other is not null then c.pos end);
end $$;

-- ── 11. 배틀: 팀 = 포켓몬 번호 (같은 종 두 마리도 됨) ───────────────────────────────────────────────────────
create or replace function public._bt_side(p_species int[], fmt text, uid uuid, p_lv int, p_fair boolean, p_mons bigint[] default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare mons jsonb := '[]'; i int; x int; c public.collection; lv int; k int; g jsonb; sd jsonb;
begin
  for i in 1 .. coalesce(cardinality(p_species), 0) loop
    x := p_species[i];
    c := null;
    if uid is not null and p_mons is not null then select * into c from public.collection where id = p_mons[i] and user_id = uid; end if;
    lv := case when p_fair then 50 when c.level is not null then c.level else coalesce(p_lv, 50) end;
    mons := mons || jsonb_build_array(public._bt_mon(x, lv, case when c.id is not null then public._cur_moves(uid, c.id) end, c.held)
                                      || jsonb_build_object('mon', c.id));
  end loop;
  for k in 0 .. jsonb_array_length(mons) - 1 loop
    g := public._bt_group(mons -> k ->> 'type');
    if g is not null and (select count(*) from jsonb_array_elements(mons) m where public._bt_group(m ->> 'type') ->> 'g' = g ->> 'g') >= 2 then
      mons := jsonb_set(mons, array[k::text], (mons -> k) || jsonb_build_object('syn', g ->> 'stat', 'synname', g ->> 'name'));
    end if;
  end loop;
  sd := jsonb_build_object('reflect', 0, 'light', 0, 'items', 0, 'uid', uid,
          'act', (select jsonb_agg(g2) from generate_series(0, least(case when fmt = 'double' then 2 else 1 end, cardinality(p_species)) - 1) g2),
          'mons', mons);
  for k in 0 .. jsonb_array_length(sd -> 'act') - 1 loop
    sd := jsonb_set(sd, array['mons', k::text], public._bt_enter(sd -> 'mons' -> k));
  end loop;
  return sd;
end $$;

-- 팀 확인: 내 박스의 서로 다른 포켓몬 1~maxn 마리 → 지금 단계의 종 번호
create or replace function public._bt_team(uid uuid, p_mons bigint[], maxn int) returns int[]
language plpgsql stable security definer set search_path = '' as $$
declare r int[];
begin
  if p_mons is null or cardinality(p_mons) not between 1 and maxn
     or (select count(distinct x) from unnest(p_mons) x) <> cardinality(p_mons) then raise exception 'BAD_TEAM'; end if;
  select array_agg(s.id order by u.o) into r
    from unnest(p_mons) with ordinality as u(x, o)
    join public.collection c on c.id = u.x and c.user_id = uid and c.released_at is null
    join public.species s on s.line_id = c.line_id and s.stage = c.stage;
  if coalesce(cardinality(r), 0) <> cardinality(p_mons) then raise exception 'BAD_TEAM'; end if;
  return r;
end $$;

-- 친구의 팀 (포켓몬 번호): 저장한 팀, 없으면 단계·레벨 높은 순
create or replace function public._bt_friend_team(uid uuid, n int) returns bigint[]
language plpgsql stable security definer set search_path = '' as $$
declare t bigint[]; r bigint[];
begin
  select team_mons into t from public.profiles where user_id = uid;
  if t is not null then
    begin perform public._bt_team(uid, t[1:n], n); return t[1:n]; exception when others then null; end;
  end if;
  select array_agg(id) into r from (
    select c.id from public.collection c where c.user_id = uid and c.released_at is null
     order by c.stage desc, c.level desc, c.id limit n) x;
  return r;
end $$;

