-- 새 포켓몬 한 마리: 비어 있는 맨 앞 칸 (BOX 1 의 1번 칸부터). 꽉 차면 BOX_FULL
create or replace function public._mon_new(uid uuid, p_line int, p_stage int, p_level int default null, p_egg boolean default false)
returns public.collection
language plpgsql security definer set search_path = '' as $$
declare c public.collection; v_pos int;
begin
  perform pg_advisory_xact_lock(hashtext('box:' || uid::text));
  if public._box_count(uid) >= public._box_max() then raise exception 'BOX_FULL'; end if;
  select min(g) into v_pos from generate_series(0, 899) g
   where not exists (select 1 from public.collection x where x.user_id = uid and x.released_at is null and x.pos = g);
  if v_pos is null then raise exception 'BOX_FULL'; end if;
  insert into public.collection (user_id, line_id, stage, level, from_egg, pos)
  values (uid, p_line, p_stage, coalesce(p_level, 5), coalesce(p_egg, false), v_pos)
  returning * into c;
  return c;
end $$;

