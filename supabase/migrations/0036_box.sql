-- ── 4. 성장 (포켓몬 한 마리) ─────────────────────────────────────────────────────────────────────────────────
create or replace function public._add_levels(uid uuid, p_mon bigint, n int) returns int
language plpgsql security definer set search_path = '' as $$
declare lv int;
begin
  update public.collection set level = least(100, level + n), exp = case when level + n >= 100 then 0 else exp end, updated_at = now()
   where id = p_mon and user_id = uid and released_at is null and level < 100 returning level into lv;
  return lv;
end $$;

create or replace function public._gain_exp(uid uuid, p_mon bigint, amt int) returns int
language plpgsql security definer set search_path = '' as $$
declare c public.collection; lv int; ex int; need int; up int := 0; mul int := coalesce((public._setting('exp_need_mul'))::int, 8);
begin
  if amt is null or amt <= 0 or p_mon is null then return 0; end if;
  select * into c from public.collection where id = p_mon and user_id = uid and released_at is null for update;
  if not found or c.level >= 100 then return 0; end if;
  lv := c.level; ex := c.exp + amt;
  while lv < 100 loop
    need := mul * lv;
    exit when ex < need;
    ex := ex - need; lv := lv + 1; up := up + 1;
  end loop;
  if lv >= 100 then ex := 0; end if;
  update public.collection set level = lv, exp = ex, updated_at = now() where id = p_mon;
  return up;
end $$;

create or replace function public._known_moves(uid uuid, p_mon bigint) returns int[]
language sql stable security definer set search_path = '' as $$
  select coalesce(array_agg(distinct m order by m), '{}') from (
    select sm.move_id m from public.collection c join public.species s on s.line_id = c.line_id and s.stage <= c.stage
      join public.species_moves sm on sm.species_id = s.id where c.id = p_mon and c.user_id = uid
    union all
    select ls.move_id from public.collection c join public.learnset ls on ls.line_id = c.line_id and ls.how = 'level' and ls.lv <= c.level
     where c.id = p_mon and c.user_id = uid
    union all
    select unnest(c.learned) from public.collection c where c.id = p_mon and c.user_id = uid) x
   where exists (select 1 from public.moves where id = x.m)
$$;

create or replace function public._cur_moves(uid uuid, p_mon bigint) returns int[]
language plpgsql stable security definer set search_path = '' as $$
declare c public.collection; r int[]; k int[];
begin
  select * into c from public.collection where id = p_mon and user_id = uid;
  if not found then return '{}'; end if;
  if c.moves is not null then
    k := public._known_moves(uid, p_mon);
    r := array(select x from unnest(c.moves) with ordinality u(x, o) where x = any (k) order by o);
  end if;
  if coalesce(cardinality(r), 0) = 0 then
    r := array(select sm.move_id from public.species s join public.species_moves sm on sm.species_id = s.id
                where s.line_id = c.line_id and s.stage = c.stage order by sm.slot);
  end if;
  return r;
end $$;

-- 장소 QR 3곳마다 배틀 팀 +1 (0027 그대로, 팀 = 포켓몬 번호)
create or replace function public._ticket_growth() returns trigger
language plpgsql security definer set search_path = '' as $$
declare qp public.qr_points; k text; n int; per int := greatest(1, coalesce((public._setting('lv_places_n'))::int, 3)); x bigint;
begin
  if new.special is not null then return new; end if;
  select * into qp from public.qr_points where id = new.qr_id;
  if random() < coalesce((public._setting('drop_place'))::numeric, 0.3) then
    k := case when qp.drop_item is not null and random() < 0.5 then qp.drop_item else public._roll_item('place') end;
    perform public._give_item(new.user_id, k, 1, 'place');
  end if;
  if public._lv_on('lv_from_places') and not exists (
       select 1 from public.tickets t where t.user_id = new.user_id and t.qr_id = new.qr_id and t.id <> new.id and t.special is null
          and (t.created_at at time zone 'Asia/Seoul')::date = (now() at time zone 'Asia/Seoul')::date) then
    select count(distinct qr_id) into n from public.tickets t where t.user_id = new.user_id and t.special is null
       and (t.created_at at time zone 'Asia/Seoul')::date = (now() at time zone 'Asia/Seoul')::date;
    if n > 0 and n % per = 0 then
      foreach x in array coalesce(public._team_mons(new.user_id), '{}') loop
        perform public._add_levels(new.user_id, x, 1);
      end loop;
      insert into public.item_log (user_id, item, qty, why) values (new.user_id, '_team_level', n, 'places');
    end if;
  end if;
  if not exists (select 1 from public.tickets t where t.user_id = new.user_id and t.qr_id = new.qr_id and t.id <> new.id and t.special is null) then
    perform public._egg_place(new.user_id);
  end if;
  return new;
end $$;

-- ── 5. 점수 · 도감 · 도전과제: 계열마다 하나 (놓아준 것도 '잡은 적 있음') ────────────────────────────────────
create or replace function public._recompute(uid uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare s int; d int;
begin
  select coalesce(sum((public._setting('stage_points') ->> c.stage)::int
                      + coalesce((public._setting('rarity_bonus') ->> l.rarity)::int, 0)), 0),
         coalesce(sum(c.stage), 0)
    into s, d
  from (select line_id, max(stage) as stage from public.collection where user_id = uid group by line_id) c
  join public.lines l on l.id = c.line_id;
  update public.profiles
     set score_at = case when s > score then now() else score_at end,
         score = s, dex_count = d
   where user_id = uid;
  perform public._dex_rewards(uid);
end $$;

