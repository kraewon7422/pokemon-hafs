-- 0034 _bt_finish 그대로, 경험치는 그 배틀에 나간 포켓몬 한 마리에게 ('mon'; 0036 전 배틀은 그 계열의 레벨 높은 것)
create or replace function public._bt_finish(bid bigint, w smallint) returns void
language plpgsql security definer set search_path = '' as $$
declare got boolean; b public.battles; uid uuid; v_opp uuid; rw jsonb; n int; v_day date := (now() at time zone 'Asia/Seoul')::date;
  turns int; s int; pu uuid; m jsonb; foe_lv numeric; base numeric; up int; ex jsonb; exps jsonb := '{}'; its jsonb := '{}'; k text; won boolean;
  pdrop numeric; npr int; pmax int := coalesce((public._setting('practice_exp_daily'))::int, 10); v_mon bigint;
begin
  select * into b from public.battles where id = bid for update;
  if b.status <> 'active' then return; end if;
  rw := jsonb_build_object('ticket', false);
  if w is not null then
    uid := case when w = 0 then b.p1 when b.mode = 'pvp' then b.p2 end;
    v_opp := case when w = 0 then b.p2 else b.p1 end;
    if uid is null then rw := jsonb_build_object('ticket', false, 'why', 'lost');
    elsif b.mode = 'cpu' or v_opp is null then rw := jsonb_build_object('ticket', false, 'why', 'practice');
    elsif exists (select 1 from public.battle_rewards r where r.user_id = uid and r.opp = v_opp and r.day = v_day) then
      rw := jsonb_build_object('ticket', false, 'why', 'same_opp');
    else
      select count(*) into n from public.battle_rewards r where r.user_id = uid and r.day = v_day;
      if n >= coalesce((public._setting('battle_daily_max'))::int, 3) then
        rw := jsonb_build_object('ticket', false, 'why', 'daily_max');
      else
        insert into public.battle_rewards (user_id, opp, day, battle_id) values (uid, v_opp, v_day, bid);
        got := random() < coalesce((public._setting('battle_stone_chance'))::numeric, 1);   -- 0034: 이기면 가끔 진화의돌
        update public.profiles set evo_tickets = evo_tickets + (case when got then 1 else 0 end), battle_wins = battle_wins + 1, battle_wins_at = now() where user_id = uid;
        rw := jsonb_build_object('ticket', got, 'today', n + 1, 'why', case when got then null else 'luck' end);
        insert into public.events (kind, data) values ('battle_won', jsonb_build_object('battle', bid, 'mode', b.mode));
      end if;
    end if;
  end if;
  turns := coalesce((b.state ->> 'turn')::int, 0);
  -- (plpgsql: IF 조건 안의 CASE … THEN 은 IF 의 THEN 으로 잘못 읽힌다 → 미리 계산)
  pdrop := case when b.mode = 'cpu' then coalesce((public._setting('drop_practice'))::numeric, 0.15)
                else coalesce((public._setting('drop_battle'))::numeric, 0.5) end;
  -- 연습 배틀: 경험치·물건은 하루 practice_exp_daily 판까지 (연습만 반복해서 레벨·회복약을 끝없이 모으지 않게)
  if b.mode = 'cpu' and turns >= 2 then
    select count(*) into npr from public.battles x
     where x.p1 = b.p1 and x.mode = 'cpu' and x.status = 'over' and x.id <> bid
       and x.updated_at >= (date_trunc('day', now() at time zone 'Asia/Seoul') at time zone 'Asia/Seoul')
       and coalesce((x.reward ->> 'practice_counted')::boolean, false);
    if npr >= pmax then
      rw := rw || jsonb_build_object('exp_why', 'practice_max', 'practice_max', pmax);
      update public.battles set status = 'over', winner = w, reward = rw, deadline = null, updated_at = now() where id = bid;
      return;
    end if;
    rw := rw || jsonb_build_object('practice_counted', true, 'practice_left', pmax - npr - 1);
  end if;
  for s in 0 .. 1 loop
    pu := case when s = 0 then b.p1 when b.mode = 'pvp' then b.p2 end;
    continue when pu is null or turns < 2;
    won := w is not null and w = s;
    if public._lv_on('lv_from_battle') then
      select avg((x ->> 'lv')::numeric) into foe_lv from jsonb_array_elements(b.state -> 'sides' -> (1 - s) -> 'mons') x;
      base := coalesce((public._setting('exp_battle_mul'))::numeric, 4) * coalesce(foe_lv, 50)
              * (case b.mode when 'cpu' then coalesce((public._setting('exp_practice'))::numeric, 0.5) when 'pvp' then 1.5 else 1 end)
              * (case when won then 1 else coalesce((public._setting('exp_lose'))::numeric, 0.4) end);
      ex := '[]';
      for m in select x from jsonb_array_elements(b.state -> 'sides' -> s -> 'mons') x where coalesce((x ->> 'out')::boolean, false) loop
        v_mon := coalesce((m ->> 'mon')::bigint,
                          (select c.id from public.collection c where c.user_id = pu and c.line_id = (m ->> 'line')::int and c.released_at is null
                            order by c.level desc, c.id limit 1));
        up := public._gain_exp(pu, v_mon, round(base)::int);
        ex := ex || jsonb_build_object('line', (m ->> 'line')::int, 'mon', v_mon, 'name', m ->> 'name', 'exp', round(base)::int, 'up', up,
                                       'lv', (select level from public.collection where id = v_mon and user_id = pu));
      end loop;
      exps := exps || jsonb_build_object(s::text, ex);
    end if;
    if won and random() < pdrop then
      k := public._roll_item(case when b.mode = 'cpu' then 'practice' else 'battle' end);
      if k is not null then
        perform public._give_item(pu, k, 1, 'battle');
        its := its || jsonb_build_object(s::text, k);
      end if;
    end if;
  end loop;
  rw := rw || jsonb_build_object('exp', exps, 'item', its);
  update public.battles set status = 'over', winner = w, reward = rw, deadline = null, updated_at = now() where id = bid;
end $$;

-- ── 12. 레이드: 참가 포켓몬 = 한 마리 (mon_id) ──────────────────────────────────────────────────────────────
create or replace function public._raid_per_tap(uid uuid, p_mon bigint, boss int) returns int
language plpgsql stable security definer set search_path = '' as $$
declare a public.species; b public.species; at text; bt text; m numeric := 1; atk int; def int;
begin
  if p_mon is null then return 3; end if;
  select s.* into a from public.collection c join public.species s on s.line_id = c.line_id and s.stage = c.stage
   where c.id = p_mon and c.user_id = uid;
  if not found then return 3; end if;
  select * into b from public.species where id = boss;
  at := coalesce(a.btype, (select btype from public.lines where id = a.line_id), '노말');
  bt := coalesce(b.btype, (select btype from public.lines where id = b.line_id), '노말');
  m := public._bt_tm(at, bt);
  if coalesce(a.atk, 0) >= coalesce(a.spa, 0) then
    atk := floor((2 * coalesce(a.atk, 50) + 31) / 2) + 5; def := floor((2 * coalesce(b.def, 50) + 31) / 2) + 5;
  else
    atk := floor((2 * coalesce(a.spa, 50) + 31) / 2) + 5; def := floor((2 * coalesce(b.spd, 50) + 31) / 2) + 5;
  end if;
  return greatest(1, round(10.0 * atk / greatest(def, 1) * m));   -- 효과 없음(×0)이어도 탭당 1은 들어간다
end $$;

create or replace function public._raid_json(r public.raids, uid uuid) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'id', r.id, 'species_id', r.species_id, 'kind', r.kind, 'title', r.title, 'tv', r.tv,
    'hp', r.hp, 'hp_max', r.hp_max, 'status', r.status, 'starts_at', r.starts_at, 'ends_at', r.ends_at, 'ended_at', r.ended_at,
    'server_time', now(),
    'players', (select count(*) from public.raid_players where raid_id = r.id),
    'me', (select jsonb_build_object('damage', p.damage, 'taps', p.taps, 'line_id', p.line_id, 'mon_id', p.mon_id, 'rewarded', p.rewarded,
                                     'per_tap', public._raid_per_tap(uid, p.mon_id, r.species_id))
           from public.raid_players p where p.raid_id = r.id and p.user_id = uid),
    'top', coalesce((select jsonb_agg(jsonb_build_object('display', public._display_name(pr), 'damage', p.damage) order by p.damage desc)
                     from (select * from public.raid_players where raid_id = r.id order by damage desc limit 5) p
                     join public.profiles pr on pr.user_id = p.user_id), '[]'))
$$;

create or replace function public.raid_join(p_q text, p_t text, p_mon bigint default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid(); r public.raids; ok boolean := false; w bigint; c public.collection;
  win_sec int := (public._setting('rotating_window_sec'))::int;
begin
  if uid is null or not exists (select 1 from public.profiles where user_id = uid) then raise exception 'NOT_AUTHENTICATED'; end if;
  perform public._assert_open();
  perform public._raid_sweep();
  if coalesce(p_q, '') !~* '^R[0-9]{1,5}$' then raise exception 'RAID_NOT_FOUND'; end if;
  select * into r from public.raids where id = substr(p_q, 2)::bigint;
  if not found then raise exception 'RAID_NOT_FOUND'; end if;
  if r.status <> 'active' or now() < r.starts_at then raise exception 'RAID_OVER'; end if;
  if r.tv then
    w := floor(extract(epoch from now()) / win_sec);
    for i in 0 .. greatest(1, 90 / win_sec) loop
      if public._raid_token(r, w - i) = lower(p_t) then ok := true; exit; end if;
    end loop;
  else
    ok := r.token = lower(p_t);
  end if;
  if not ok then raise exception 'RAID_BAD_TOKEN'; end if;
  select * into c from public.collection where id = p_mon and user_id = uid and released_at is null;
  insert into public.raid_players (raid_id, user_id, line_id, mon_id)
  values (r.id, uid, c.line_id, c.id)
  on conflict (raid_id, user_id) do nothing;
  return public._raid_json(r, uid);
end $$;

