create or replace function public.raid_attack(p_raid bigint, p_taps int, p_mon bigint default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid(); r public.raids; p public.raid_players; c public.collection;
  cap int := coalesce((public._setting('raid_tap_cap'))::int, 8);
  elapsed numeric; allowed int; per int; dmg int; left_hp int;
begin
  select * into p from public.raid_players where raid_id = p_raid and user_id = uid for update;
  if not found then raise exception 'RAID_NOT_JOINED'; end if;
  select * into r from public.raids where id = p_raid;
  if r.status = 'active' and r.ends_at <= now() then
    perform public._raid_finish(r.id, false);
    select * into r from public.raids where id = p_raid;
  end if;
  if r.status <> 'active' then return public._raid_json(r, uid); end if;

  if p_mon is not null then
    select * into c from public.collection where id = p_mon and user_id = uid and released_at is null;
    if found then p.mon_id := c.id; p.line_id := c.line_id; end if;
  end if;
  elapsed := least(10, extract(epoch from now() - coalesce(p.last_tap_at, p.joined_at)));
  allowed := least(greatest(coalesce(p_taps, 0), 0), floor(elapsed * cap)::int + cap);
  per := public._raid_per_tap(uid, p.mon_id, r.species_id);
  dmg := allowed * per;
  update public.raid_players set damage = damage + dmg, taps = taps + allowed, last_tap_at = now(), line_id = p.line_id, mon_id = p.mon_id
   where raid_id = p_raid and user_id = uid;
  if dmg > 0 then
    update public.raids set hp = greatest(0, hp - dmg) where id = p_raid and status = 'active' returning hp into left_hp;
    if left_hp = 0 then perform public._raid_finish(p_raid, true); end if;
  end if;
  select * into r from public.raids where id = p_raid;
  return public._raid_json(r, uid) || jsonb_build_object('accepted', allowed, 'dealt', dmg);
end $$;

create or replace function public._raid_growth() returns trigger
language plpgsql security definer set search_path = '' as $$
declare p record; minimum int := coalesce((public._setting('raid_min_taps'))::int, 1);
begin
  if old.status <> 'active' or new.status not in ('won', 'failed') then return new; end if;
  for p in select * from public.raid_players where raid_id = new.id and taps >= minimum loop
    if public._lv_on('lv_from_raid') and p.mon_id is not null then
      perform public._add_levels(p.user_id, p.mon_id, coalesce((public._setting('raid_levels'))::int, 1));
    end if;
    if new.status = 'won' then
      perform public._give_item(p.user_id, 'candy', 1, 'raid');
      if random() < coalesce((public._setting('drop_raid_tm'))::numeric, 0.3) then
        perform public._give_item(p.user_id, public._roll_item('raid'), 1, 'raid');
      end if;
    end if;
  end loop;
  return new;
end $$;


