create or replace function public.safari_result(p_id bigint, p_throws int, p_caught boolean, p_grade text default 'none', p_curve boolean default false)
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p public.profiles := public._me_locked(); uid uuid := p.user_id; e public.raid_encounters; res jsonb;
  th int; caught boolean := coalesce(p_caught, true); k int; server_fled boolean := false;
begin
  select * into e from public.raid_encounters where id = p_id and user_id = uid and kind = 'safari' for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if e.status <> 'pending' then   -- 0038: 이미 끝난 만남 = 적어 둔 결과 그대로 (다시 보내도 볼을 더 쓰지 않음)
    return coalesce(e.result, jsonb_build_object('caught', e.status = 'caught', 'fled', e.status = 'fled',
                                                 'line', (select line_id from public.species where id = e.species_id),
                                                 'species_id', e.species_id, 'new', false, 'level', null, 'exp', 0))
           || jsonb_build_object('safari', public._safari_json(uid), 'replay', true);
  end if;
  th := least(e.balls, greatest(0, coalesce(p_throws, e.balls)));
  if caught and th - 1 > e.turns then
    for k in e.turns .. th - 2 loop
      if random() < public._safari_flee_p(e.species_id, k) then caught := false; server_fled := true; th := k + 1; exit; end if;
    end loop;
  end if;
  update public.raid_encounters set throws = th, turns = greatest(turns, th - case when caught then 1 else 0 end) where id = e.id;
  res := public.encounter_result(p_id, caught, p_grade, p_curve);
  return res || jsonb_build_object('safari', public._safari_json(uid), 'server_fled', server_fled);
end $$;

-- ── 10. 동기화 · 상태 ─────────────────────────────────────────────────────────────────────────────────────
-- 0005 sync + 새로 찍은 장소 QR → 방랑 전설 굴리기, 끝에 퀘스트 확인
create or replace function public.sync(p_scans jsonb default '[]', p_ver text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  p public.profiles := public._me_locked();
  s jsonb; st text; acks jsonb := '[]'; state jsonb; ver text; existed boolean;
  open boolean := public._is_open();
begin
  if jsonb_typeof(p_scans) = 'array' and jsonb_array_length(p_scans) > 50 then raise exception 'TOO_MANY'; end if;
  perform public._expire_old(p.user_id);
  if jsonb_typeof(p_scans) = 'array' then
    for s in select * from jsonb_array_elements(p_scans) limit 20 loop
      begin
        existed := exists (select 1 from public.tickets where nonce = lower(s ->> 'n'));
        st := case when not open then 'closed'
                   else public._admit(p.user_id, s ->> 'n', s ->> 'q', s ->> 't', (s ->> 'at')::timestamptz) end;
      exception when others then
        st := 'bad_format'; existed := true;
      end;
      if st = 'ok' and not existed then
        begin
          perform public._roam_roll(p.user_id, (select qr_id from public.tickets where nonce = lower(s ->> 'n') and user_id = p.user_id));
        exception when others then null;   -- 방랑 전설은 덤: 실패해도 스캔은 그대로
        end;
      end if;
      acks := acks || jsonb_build_array(jsonb_build_object('nonce', s ->> 'n', 'status', st));
    end loop;
  end if;
  begin
    perform public._quest_check(p.user_id);
  exception when others then null;
  end;
  update public.profiles set last_seen = now() where user_id = p.user_id;
  state := public._state(p.user_id);
  ver := md5(state::text);
  if p_ver is not distinct from ver then
    return jsonb_build_object('acks', acks, 'ver', ver, 'same', true, 'server_time', now());
  end if;
  return jsonb_build_object('acks', acks, 'ver', ver, 'state', state || jsonb_build_object('server_time', now()));
end $$;

