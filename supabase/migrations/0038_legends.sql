-- 받침이 있으면 a (을 · 이 · 은), 없으면 b
create or replace function public._josa(w text, a text, b text) returns text
language sql immutable set search_path = '' as $$
  select coalesce(w, '') || case when w is null or w = '' then b
    when ascii(right(w, 1)) between 44032 and 55203 and (ascii(right(w, 1)) - 44032) % 28 <> 0 then a
    when ascii(right(w, 1)) between 44032 and 55203 then b
    when right(w, 1) ~ '[0-9]' then case when right(w, 1) in ('0', '1', '3', '6', '7', '8') then a else b end
    else b end
$$;

