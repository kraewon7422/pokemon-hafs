-- ── 9. 사파리존: 지난 구간의 만남 정리 · 구역 · 던진 수 · 같은 결과 ─────────────────────────────────────────
create or replace function public._safari_expire(uid uuid) returns int
language plpgsql security definer set search_path = '' as $$
declare e public.raid_encounters; used int; n int := 0; ps timestamptz := public._safari_period();
begin
  for e in select * from public.raid_encounters where user_id = uid and kind = 'safari' and status = 'pending' and created_at < ps for update loop
    used := least(e.balls, greatest(0, coalesce(e.throws, 0)));
    insert into public.safari_days (user_id, day, period_start, balls_used)
    values (uid, (public._safari_period(e.created_at) at time zone 'Asia/Seoul')::date, public._safari_period(e.created_at), used)
      on conflict (user_id, period_start) do update set balls_used = public.safari_days.balls_used + excluded.balls_used;
    update public.raid_encounters set status = 'fled', resolved_at = now(), grade = 'none', throws = used,
           result = jsonb_build_object('caught', false, 'fled', true, 'line', (select line_id from public.species where id = e.species_id),
                                       'species_id', e.species_id, 'new', false, 'level', null, 'exp', 0, 'expired', true)
     where id = e.id;
    n := n + 1;
  end loop;
  return n;
end $$;

