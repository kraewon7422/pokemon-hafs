-- 야생 계열 (0032) — 퀘스트 · 사파리 · 방랑 · 소포 전설과 울트라비스트는 뺌
create or replace function public._wild_line() returns int
language sql volatile security definer set search_path = '' as $$
  select l.id from public.lines l
   where l.subject = '야생' and l.active and not l.withdrawn and not l.bonus and not l.secret and not l.mythic
     and not l.ultra and l.legend_src is null
     and coalesce((public._setting('wild_weights') ->> l.rarity)::numeric, 0) > 0
   order by -ln(1 - random()) / (public._setting('wild_weights') ->> l.rarity)::numeric limit 1
$$;

-- 사파리존 구역별: ultra = 울트라비스트만 · cave/deep = 바위·땅·고스트·악·강철·물 타입 safari_cave_type_mult 배 · 그 밖 = _wild_line
create or replace function public._wild_line_zone(p_zone text) returns int
language sql volatile security definer set search_path = '' as $$
  select case
    when p_zone = 'ultra' then (select l.id from public.lines l where l.ultra and l.active and not l.withdrawn order by random() limit 1)
    when p_zone in ('cave', 'deep') then (
      select l.id from public.lines l
       where l.subject = '야생' and l.active and not l.withdrawn and not l.bonus and not l.secret and not l.mythic
         and not l.ultra and l.legend_src is null
         and coalesce((public._setting('wild_weights') ->> l.rarity)::numeric, 0) > 0
       order by -ln(1 - random()) / ((public._setting('wild_weights') ->> l.rarity)::numeric
                 * case when string_to_array(coalesce(l.btype, ''), '/') && array['바위', '땅', '고스트', '악', '강철', '물']
                        then greatest(1, coalesce((public._setting('safari_cave_type_mult'))::numeric, 4)) else 1 end) limit 1)
    else public._wild_line() end
$$;

-- 메타몽 변신을 굴릴 수 있는 계열인가 (야생 · 전설 아님) → 굴려서 메타몽 종 번호 (아니면 null)
create or replace function public._ditto_roll(p_line int) returns int
language plpgsql volatile security definer set search_path = '' as $$
declare l public.lines; d int := public._dex_sp(132);
begin
  select * into l from public.lines where id = p_line;
  if not found or d is null or l.subject <> '야생' or l.rarity = 'legendary' or l.mythic or l.legend_src is not null
     or l.id = (select line_id from public.species where id = d) then return null; end if;
  if random() < least(1, greatest(0, coalesce((public._setting('ditto_disguise_chance'))::numeric, 0.005))) then return d; end if;
  return null;
end $$;

