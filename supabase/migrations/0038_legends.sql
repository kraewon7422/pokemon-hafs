    when 'raid_slots' then jsonb_build_object('cond', '서로 다른 시간대의 레이드에 ' || need || '번 참가해야 한대', 'prog', '참가한 시간대 ' || least(cur, need) || '/' || need)
    when 'qr_all' then jsonb_build_object('cond', '지도에 있는 장소 QR을 모두 찍어야 한대', 'prog', '찍은 장소 ' || least(cur, need) || '/' || need)
    when 'type_catch' then (select jsonb_build_object('cond', t || ' 타입 포켓몬을 ' || need || '마리 잡아야 한대', 'prog', t || ' 타입 ' || least(cur, need) || '/' || need)
                              from (select string_agg(x, '·') t from jsonb_array_elements_text(coalesce(q -> 'types', '[]')) x) z)
    when 'safari_catches' then jsonb_build_object('cond', '사파리존에서 포켓몬을 ' || need || '마리 잡아야 한대', 'prog', '사파리존에서 잡은 포켓몬 ' || least(cur, need) || '/' || need)
    when 'caught_all' then (select jsonb_build_object('cond', public._josa(t, '을', '를') || ' 모두 잡아야 한대', 'prog', '잡은 전설 ' || least(cur, need) || '/' || need)
                              from (select string_agg(public._sp_name(public._dex_sp(x::int)), '·' order by o) t
                                      from jsonb_array_elements_text(coalesce(q -> 'of', '[]')) with ordinality u(x, o)) z)
    else jsonb_build_object('cond', '아직 아무도 모른대', 'prog', '') end
$$;

-- 퀘스트 전설 하나하나: { dex, species_id, line_id, name, kind, reward, cur, need, ok, done, caught, seen, granted, cond, prog }
create or replace function public._quest_rows(uid uuid) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(r order by o), '[]') from (
    select u.o, jsonb_build_object(
      'dex', (q ->> 'dex')::int, 'species_id', sp.id, 'line_id', sp.line_id, 'name', sp.name, 'kind', q ->> 'kind', 'reward', q ->> 'reward',
      'cur', z.cur, 'need', z.need, 'done', z.done, 'ok', z.done or z.cur >= z.need,
      'caught', exists (select 1 from public.collection c where c.user_id = uid and c.line_id = sp.line_id),
      'granted', exists (select 1 from public.tickets t where t.user_id = uid and t.special = 'quest' and t.fixed_species = sp.id and t.status <> 'cancelled'),
      'seen', exists (select 1 from public._seen_species(uid) x where x = sp.id),
      'cond', public._quest_text(q, z.cur, z.need) ->> 'cond', 'prog', public._quest_text(q, z.cur, z.need) ->> 'prog') r
    from jsonb_array_elements(coalesce(public._setting('legend_quests'), '[]')) with ordinality u(q, o)
    join public.species sp on sp.id = public._dex_sp((q ->> 'dex')::int)
    cross join lateral (select public._quest_cur(uid, q) cur, public._quest_need(q) need,
                               exists (select 1 from public.legend_quest_done d where d.user_id = uid and d.dex = (q ->> 'dex')::int) done) z) x
$$;

create or replace function public._quest_ok(uid uuid, q jsonb) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.legend_quest_done d where d.user_id = uid and d.dex = (q ->> 'dex')::int)
      or public._quest_cur(uid, q) >= public._quest_need(q)
$$;

-- 새로 채운 퀘스트: 기록 + (ticket) 특별 티켓 → 알림은 티켓이 씀 / (map) '깨어났다' 알림
create or replace function public._quest_check(uid uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare q jsonb; sp int; ln int; nm text; nn text;
begin
  for q in select x from jsonb_array_elements(coalesce(public._setting('legend_quests'), '[]')) x loop
    continue when exists (select 1 from public.legend_quest_done d where d.user_id = uid and d.dex = (q ->> 'dex')::int);
    continue when public._quest_cur(uid, q) < public._quest_need(q);
    sp := public._dex_sp((q ->> 'dex')::int);
    continue when sp is null;
    insert into public.legend_quest_done (user_id, dex) values (uid, (q ->> 'dex')::int) on conflict do nothing;
    select line_id, name into ln, nm from public.species where id = sp;
    if q ->> 'reward' = 'ticket' then
      if not exists (select 1 from public.tickets where user_id = uid and special = 'quest' and fixed_species = sp) then
        insert into public.tickets (nonce, user_id, qr_id, token, special, fixed_species)
        values (public._rand(12, 'abcdefghijklmnopqrstuvwxyz0123456789'), uid, 'QUEST', 'quest', 'quest', sp) returning nonce into nn;
        perform public._notice(uid, 'quest', sp, '전설의 포켓몬이 나타났다!',
          '퀘스트를 해냈어요! ' || nm || ' 특별 티켓을 받았어요! 티켓 주머니에 넣어 두었어요 — 부스에서 가방 QR을 보여 주면 받을 수 있어요.',
          jsonb_build_object('nonce', nn, 'pending', true, 'legend', true, 'dex', (q ->> 'dex')::int));
      end if;
    elsif not exists (select 1 from public.collection where user_id = uid and line_id = ln) then
      perform public._notice(uid, 'legend_ready', sp, public._josa(nm, '이', '가') || ' 깨어났다!',
        '퀘스트를 해냈어요! 이제 사파리존에서 ' || public._josa(nm, '을', '를') || ' 만날 수 있어요. 사육사에게 어디 있는지 물어봐요.',
        jsonb_build_object('dex', (q ->> 'dex')::int, 'tab', 'map'));
    end if;
  end loop;
end $$;

-- ── 5. 방랑 전설 ───────────────────────────────────────────────────────────────────────────────────────────
-- 그 시각 (한 시간 단위) 에 그 전설이 있는 장소 QR — roam_seed 로 정해짐 (같은 시간 = 늘 같은 곳)
create or replace function public._roam_spot(p_dex int, p_at timestamptz default now()) returns text
language sql stable security definer set search_path = '' as $$
  select q.id from public.qr_points q
   where q.kind = 'static' and q.visible_on_map and q.active
   order by md5(coalesce(public._setting('roam_seed') #>> '{}', '') || ':' || p_dex || ':'
                || to_char(date_trunc('hour', p_at at time zone 'Asia/Seoul'), 'YYYYMMDDHH24') || ':' || q.id), q.id
   limit 1
$$;

-- 소문에 쓰는 구역 (정확한 장소가 아니라 건물 · 지도 쪽)
create or replace function public._roam_area(p_qr text) returns text
language sql stable security definer set search_path = '' as $$
  select case
    when split_part(q.name, ' ', 1) ~ '홀$' or split_part(q.name, ' ', 1) in ('기숙사', '운동장') then split_part(q.name, ' ', 1) || ' 근처'
    else '지도 ' || case when q.map_y < 0.35 then '위쪽' when q.map_y > 0.65 then '아래쪽' else '가운데' end
         || case when q.map_x < 0.35 then ' 왼편' when q.map_x > 0.65 then ' 오른편' else '' end || ' 어딘가' end
  from public.qr_points q where q.id = p_qr
$$;

create or replace function public._roamers_json(uid uuid) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'dex', s.dex, 'species_id', s.id, 'name', s.name,
      'caught', exists (select 1 from public.collection c where c.user_id = uid and c.line_id = l.id),
      'until', date_trunc('hour', now()) + interval '1 hour',
      'rumour', public._roam_area(public._roam_spot(s.dex)) || '에서 '
                || case s.dex when 243 then '번개 같은 울음소리가 들렸대!' when 244 then '뜨거운 바람이 휘몰아쳤대!'
                              when 245 then '맑은 북풍이 스쳐 지나갔대!' else '이상한 기운이 느껴졌대!' end)
      order by s.dex), '[]')
  from public.lines l join public.species s on s.line_id = l.id and s.stage = 1
  where l.legend_src = 'roam' and l.active and not l.withdrawn
$$;

-- 장소 QR 을 새로 찍음 → 그 시간 그 QR 에 방랑 전설이 있으면 roam_chance 확률로 만남 (계정마다 한 번 잡음, 한 시간에 한 번 기회)
create or replace function public._roam_roll(uid uuid, p_qr text) returns void
language plpgsql security definer set search_path = '' as $$
declare r record; ch numeric := least(1, greatest(0, coalesce((public._setting('roam_chance'))::numeric, 0.3)));
begin
  if p_qr is null or ch <= 0 then return; end if;
  for r in select s.id sp, s.dex, l.id ln from public.lines l join public.species s on s.line_id = l.id and s.stage = 1
            where l.legend_src = 'roam' and l.active and not l.withdrawn loop
    continue when public._roam_spot(r.dex) is distinct from p_qr;
    continue when exists (select 1 from public.collection where user_id = uid and line_id = r.ln);
    continue when exists (select 1 from public.raid_encounters where user_id = uid and kind = 'roam' and species_id = r.sp
                           and (status = 'pending' or created_at >= date_trunc('hour', now())));
    if random() < ch then
      insert into public.raid_encounters (user_id, raid_id, species_id, balls, kind)
      values (uid, null, r.sp, greatest(1, coalesce((public._setting('roam_balls'))::int, 8)), 'roam');
    end if;
  end loop;
end $$;

