-- 특별 티켓 → 알림 (트랜잭션 끝에서: 바로 박스로 들어갔는지 / 티켓 주머니에 남았는지 보고)
create or replace function public._ticket_notice() returns trigger
language plpgsql security definer set search_path = '' as $$
declare t public.tickets; sp int; nm text; rar text; title text; body text; tail text; legend boolean;
begin
  select * into t from public.tickets where id = new.id;
  if not found or t.special is null or t.status = 'cancelled' then return null; end if;
  sp := coalesce(t.result_species, t.fixed_species);
  select s.name, l.rarity into nm, rar from public.species s join public.lines l on l.id = s.line_id where s.id = sp;
  legend := rar = 'legendary';
  if t.special in ('wild', 'safari') and not legend then return null; end if;
  if t.special = 'quest' then return null; end if;   -- 퀘스트 티켓 알림은 _quest_check 가 바로 씀 (같은 sync 에서 보이게)
  if t.status = 'redeemed' then tail := ' 박스에 들어갔어요.';
  else tail := ' 티켓 주머니에 넣어 두었어요 — 부스에서 가방 QR을 보여 주면 받을 수 있어요.'; end if;
  case t.special
    when 'dex50' then title := '도감 50% 달성!'; body := nm || '의 특별 티켓을 받았어요!';
    when 'dex100' then title := '도감 완성!'; body := nm || '의 특별 티켓을 받았어요!';
    when 'raid' then title := '레이드 승리!';
      body := case when t.status = 'redeemed' then '레이드 보스 ' || public._josa(nm, '을', '를') || ' 잡았어요!' else nm || ' 특별 티켓을 받았어요!' end;
    when 'egg' then title := '학교의 숨은 선물 발견!'; body := nm || ' 특별 티켓을 받았어요!';
    when 'quest' then title := '전설의 포켓몬이 나타났다!'; body := '퀘스트를 해냈어요! ' || nm || ' 특별 티켓을 받았어요!';
    when 'gift' then title := '이상한 소포가 도착했다!'; body := '소포 안에 ' || public._josa(nm, '이', '가') || ' 들어 있었어요!';
    when 'roam' then title := '방랑 전설을 잡았다!'; body := public._josa(nm, '을', '를') || ' 잡았어요!';
    else title := '전설의 포켓몬을 잡았다!'; body := public._josa(nm, '을', '를') || ' 잡았어요!';
  end case;
  perform public._notice(t.user_id, t.special, sp, title, body || tail,
                         jsonb_build_object('nonce', t.nonce, 'pending', t.status = 'pending', 'legend', legend));
  return null;
end $$;
drop trigger if exists tickets_notice on public.tickets;
create constraint trigger tickets_notice after insert on public.tickets
  deferrable initially deferred for each row when (new.special is not null) execute function public._ticket_notice();

create or replace function public.notice_seen(p_ids bigint[]) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); n int;
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;
  if p_ids is null or cardinality(p_ids) > 100 then raise exception 'BAD_IDS'; end if;
  update public.notices set seen_at = now() where user_id = uid and id = any(p_ids) and seen_at is null;
  get diagnostics n = row_count;
  return jsonb_build_object('seen', n);
end $$;

-- ── 4. 퀘스트 전설 ─────────────────────────────────────────────────────────────────────────────────────────
create or replace function public._quest_need(q jsonb) returns int
language sql stable security definer set search_path = '' as $$
  select case q ->> 'kind'
    when 'qr_all' then (select count(*)::int from public.qr_points where kind = 'static' and visible_on_map and active)
    when 'caught_all' then jsonb_array_length(coalesce(q -> 'of', '[]'))
    else greatest(0, coalesce((q ->> 'n')::int, 1)) end
$$;

create or replace function public._quest_cur(uid uuid, q jsonb) returns int
language sql stable security definer set search_path = '' as $$
  select case q ->> 'kind'
    when 'quiz_streak' then (   -- 가장 길게 이어진 연속 정답
      select coalesce(max(n), 0)::int from (
        select count(*) n from (
          select correct, sum(case when correct then 0 else 1 end) over (order by answered_at, id) grp
            from public.quiz_attempts where user_id = uid and answered_at is not null) x
         where correct group by grp) y)
    when 'battle_wins' then (select coalesce(battle_wins, 0) from public.profiles where user_id = uid)
    when 'catches' then (select count(*)::int from public.collection where user_id = uid and not from_egg)
    when 'raid_slots' then (select count(distinct date_trunc('hour', r.starts_at))::int
                              from public.raid_players rp join public.raids r on r.id = rp.raid_id
                             where rp.user_id = uid and rp.taps > 0)
    when 'qr_all' then (select count(distinct t.qr_id)::int from public.tickets t join public.qr_points q2 on q2.id = t.qr_id
                         where t.user_id = uid and t.special is null and t.status <> 'cancelled'
                           and q2.kind = 'static' and q2.visible_on_map and q2.active)
    when 'type_catch' then (select count(*)::int from public.collection c join public.species s on s.id = c.species_id
                             where c.user_id = uid and not c.from_egg
                               and string_to_array(coalesce(s.btype, ''), '/') && array(select jsonb_array_elements_text(coalesce(q -> 'types', '[]'))))
    when 'safari_catches' then (select count(*)::int from public.raid_encounters where user_id = uid and kind = 'safari' and status = 'caught')
    when 'caught_all' then (select count(*)::int from jsonb_array_elements_text(coalesce(q -> 'of', '[]')) d
                             where exists (select 1 from public.collection c join public.species s on s.line_id = c.line_id
                                            where c.user_id = uid and s.dex = d::int))
    else 0 end
$$;

