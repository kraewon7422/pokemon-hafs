create or replace function public._grant_special(uid uuid, sp int, kind text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.tickets (nonce, user_id, qr_id, token, special, fixed_species)
  values (public._rand(12, 'abcdefghijklmnopqrstuvwxyz0123456789'), uid,
          case kind when 'raid' then 'RAID' when 'dex50' then 'DX50' when 'egg' then 'EGG' else 'DX99' end,
          kind, kind, sp);
end $$;

create or replace function public.claim_egg(p_key text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); ln int; sp int;
begin
  if uid is null or not exists (select 1 from public.profiles where user_id = uid) then raise exception 'NOT_AUTHENTICATED'; end if;
  ln := case p_key when 'card' then 80 when 'chart' then 81 when 'map' then 82 end;
  if ln is null then raise exception 'BAD_EGG'; end if;
  select id into sp from public.species where line_id = ln and stage = 1;
  if sp is null then raise exception 'BAD_EGG'; end if;
  perform pg_advisory_xact_lock(hashtext('egg:' || uid::text || ':' || ln));
  if exists (select 1 from public.tickets where user_id = uid and special = 'egg' and fixed_species = sp)
     or exists (select 1 from public.collection where user_id = uid and line_id = ln) then
    return jsonb_build_object('granted', false, 'species_id', sp);
  end if;
  perform public._grant_special(uid, sp, 'egg');
  return jsonb_build_object('granted', true, 'species_id', sp);
end $$;

